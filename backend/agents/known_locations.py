def _alternation(names) -> str:
    return "|".join(re.escape(n) for n in sorted(names, key=len, reverse=True))


_LONG = [n for n in (*REGIONS, *ASCII_VARIANTS) if len(n) > 3]
_SHORT = [n for n in REGIONS if len(n) <= 3]
_REGION_RE = re.compile(rf"\b({_alternation(_LONG)})\b", re.IGNORECASE)
_EXACT_RE = re.compile(rf"\b({_alternation(list(CITIES) + _SHORT)})\b")
_CANONICAL = {**{n.lower(): n for n in REGIONS}, **{a.lower(): c for a, c in ASCII_VARIANTS.items()}}


def find_known_location(text: str) -> Optional[str]:
    """The first known place in ``text`` (longest name wins at a position), canonical spelling."""
    hits = [m for m in (_REGION_RE.search(text or ""), _EXACT_RE.search(text or "")) if m]
    if not hits:
        return None
    m = min(hits, key=lambda m: (m.start(), -len(m.group(1))))
    return _CANONICAL.get(m.group(1).lower(), m.group(1))
