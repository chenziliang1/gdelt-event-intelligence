    def _rule_based_plan(self, ctx: QueryContext) -> Optional[QueryPlan]:
        """Fast rule-based planner using structured context from Ollama router."""
        # Off-topic
        if ctx.intent_category == "off_topic":
            return QueryPlan(
                intent="off_topic",
                thinking="User input is a greeting or too short — no tools needed.",
                steps=[],
                visualizations=[],
                report_prompt=None,
            )

        # Event detail lookup
        if ctx.intent_category == "detail":
            # Try user_input first, then query_text (Ollama may put fingerprint there)
            search_text = (ctx.user_input or "") + " " + (ctx.query_text or "")
            evt_match = EVENT_ID_IN_TEXT.search(search_text)
            if evt_match:
                fingerprint = evt_match.group(1) or evt_match.group(2)
                # Seed for similar_events: the GlobalEventID. A bare ID is one; EVT-... and the
                # fingerprints (US-/CA-/MX-..., see precompute_sql) end with it. The old code
                # handled only US- and EVT-, so a CA- fingerprint hit int() and returned HTTP 400.
                last = fingerprint.split('-')[-1]
                seed_id = int(last) if last.isdigit() and len(last) >= 9 else None
                steps = [QueryStep(type="event_detail", params={"fingerprint": fingerprint})]
                if seed_id:
                    steps.append(QueryStep(type="similar_events", params={"seed_event_id": seed_id, "limit": 10}))
                return QueryPlan(
                    intent="event_detail_lookup",
                    thinking="User provided a specific event ID — retrieving event details + similar events.",
                    steps=steps,
                    visualizations=["event_table", "report"],
                    report_prompt=f"Summarize this specific GDELT event ({fingerprint}) and highlight related events.",
                )

        # Daily brief
        if ctx.intent_category == "brief":
            # Default to the day before the dataset anchor, never the wall clock:
            # the data is a static 2024 extract, so "today" would match zero rows.
            query_date = ctx.date_start or _iso(reference_date() - timedelta(days=1))
            end_date = ctx.date_end or query_date
            if ctx.location and ctx.date_status == "invalid":
                # The user named a day we could not use; an arbitrary other day would mislead.
                query_date, end_date = DEFAULT_DATA_START, DEFAULT_DATA_END

            # If location is provided, search events in that location instead of global daily stats
            if ctx.location:
                params: Dict[str, Any] = {
                    "limit": 20,
                    "start_date": query_date,
                    "end_date": end_date,
                    "location_hint": ctx.location,
                }
                if ctx.event_type:
                    params["event_type"] = ctx.event_type
                span = f"on {query_date}" if query_date == end_date else f"from {query_date} to {end_date}"
                return QueryPlan(
                    intent=f"events_{ctx.location}_{query_date}",
                    thinking=f"User requested events in {ctx.location} {span}. Searching for location-matched events.",
                    steps=[QueryStep(type="events", params=params)],
                    visualizations=["event_table", "report"],
                    report_prompt=f"Summarize what happened in {ctx.location} {span}.",
                )

            # No location — return global daily summary
            return QueryPlan(
                intent="daily_brief",
                thinking=f"User requested daily brief for {query_date}.",
                steps=[QueryStep(type="daily_brief", params={"query_date": query_date})],
                visualizations=["stats_cards", "report"],
                report_prompt=f"Summarize the key events on {query_date}.",
            )

        # Hot / Top events
        if ctx.intent_category == "hot":
            is_single_day = ctx.date_start is not None and ctx.date_end is not None and ctx.date_start == ctx.date_end
            if is_single_day:
                params = {"query_date": ctx.date_start, "top_n": 10}
                if ctx.location:
                    params["region_filter"] = ctx.location
                return QueryPlan(
                    intent=f"hot_events_{ctx.location or 'global'}",
                    thinking=f"User requested hot events for {ctx.date_start}." + (f" Filtering by region: {ctx.location}." if ctx.location else ""),
                    steps=[QueryStep(type="hot_events", params=params)],
                    visualizations=["event_table", "report"],
                    report_prompt=f"Summarize the hottest events on {ctx.date_start}" + (f" in {ctx.location}" if ctx.location else "") + ".",
                )
            else:
                params = {
                    "start_date": ctx.date_start or DEFAULT_DATA_START,
                    "end_date": ctx.date_end or DEFAULT_DATA_END,
                    "top_n": 10,
                }
                if ctx.location:
                    params["region_filter"] = ctx.location
                if ctx.event_type:
                    params["event_type"] = ctx.event_type
                return QueryPlan(
                    intent=f"top_events_{ctx.event_type or 'all'}_{ctx.location or 'global'}",
                    thinking=f"User requested top events" + (f" ({ctx.event_type})" if ctx.event_type else "") + (f" in {ctx.location}" if ctx.location else "") + f" from {params['start_date']} to {params['end_date']}.",
                    steps=[QueryStep(type="top_events", params=params)],
                    visualizations=["event_table", "report"],
                    report_prompt=f"Summarize the top {ctx.event_type or ''} events" + (f" in {ctx.location}" if ctx.location else "") + f" from {params['start_date']} to {params['end_date']}.",
                )

        # Regional overview
        if ctx.intent_category == "overview" and ctx.location:
            params = {"region": ctx.location}
            if ctx.date_start and ctx.date_end:
                params["start_date"] = ctx.date_start
                params["end_date"] = ctx.date_end
            else:
                params["time_range"] = "week"
            return QueryPlan(
                intent=f"regional_overview_{ctx.location}",
                thinking=f"User requested regional overview for {ctx.location}." + (f" Time range: {ctx.date_start} to {ctx.date_end}." if ctx.date_start else " Default: last week."),
                steps=[QueryStep(type="regional_overview", params=params)],
                visualizations=["stats_cards", "event_table", "report"],
                report_prompt=f"Provide a situation overview for {ctx.location}" + (f" from {ctx.date_start} to {ctx.date_end}" if ctx.date_start else " over the last week") + ".",
            )

        # Underspecified: no location, type, dates or usable text. The old code fell
        # through to a generic event search here, which made the remote-LLM fallback in
        # plan() unreachable. Returning None lets plan() hand these to it.
        if self._is_underspecified(ctx):
            return None

        # Default: events search
        params: Dict[str, Any] = {
            "limit": 50,
            "start_date": ctx.date_start or DEFAULT_DATA_START,
            "end_date": ctx.date_end or DEFAULT_DATA_END,
        }
        if ctx.location:
            params["location_hint"] = ctx.location
        if ctx.event_type:
            params["event_type"] = ctx.event_type
        if ctx.query_text:
            params["query"] = ctx.query_text
        
        intent_name = f"events_{ctx.event_type or 'all'}_{ctx.location or 'global'}"
        return QueryPlan(
            intent=intent_name,
            thinking="Event search based on extracted location, date, and event type.",
            steps=[QueryStep(type="events", params=params)],
            visualizations=["event_table", "report"],
            report_prompt=f"Summarize {ctx.event_type or 'events'} {f'in {ctx.location}' if ctx.location else ''} from {params['start_date']} to {params['end_date']}.",
        )

    @staticmethod
    def _is_underspecified(ctx: QueryContext) -> bool:
        """True when a "search" has nothing to filter on.

        Free text alone is a legitimate keyword search ("Uvalde school shooting
        response"), so on the regex-fallback path (low confidence, where query_text is
        just the whole sentence) only very short inputs count as ambiguous.
        """
        if ctx.intent_category != "search" or ctx.location or ctx.event_type or ctx.date_start:
            return False
        if not ctx.query_text:
            return True
        return ctx.confidence == "low" and len(ctx.query_text.split()) < 4

    # -----------------------------------------------------------------------
    # Date resolution (single source of truth: backend.queries.date_utils)
    # -----------------------------------------------------------------------

    def _resolve_dates(self, ctx: QueryContext, query: str) -> None:
        """Make ``ctx`` dates deterministic and validated.

        Order of trust:
          1. A date expression in the user's own words, parsed deterministically
             against the dataset anchor. This wins over the router: the 3B model
             was never given a reference date and returned 131-day windows for
             "last week".
          2. Router dates, kept only if they pass ``validate_range``.
          3. Otherwise no dates, with a note, so callers default explicitly
             instead of silently trusting a bad range labelled high-confidence.
        """
        ctx.date_note = None
        impossible = find_impossible_day(query)
        if impossible:
            # The router "repairs" 2024-02-30 to 2024-02-29 without saying so.
            ctx.date_status, ctx.date_source = "invalid", "deterministic"
            # plan() appends the window actually queried, so the note cannot disagree with the plan.
            ctx.date_note = f"'{impossible}' is not a real calendar date, so it was not used."
            ctx.date_start = ctx.date_end = None
            ctx.confidence = "low"
            return

        resolved = resolve_dates(query)
        clipped_note = ""
        if resolved is not None and resolved.kind != "month":
            # "this week" on Tuesday 2024-12-31 is Dec 30 to Jan 5; only Dec 30-31 has data.
            inside = clip_to_dataset(resolved)
            if inside is not None and inside is not resolved:
                clipped_note = f", limited to the data available ({inside.start_iso} to {inside.end_iso})"
                resolved = inside
        if resolved is not None:
            check = validate_range(resolved.start_iso, resolved.end_iso, resolved.kind if resolved.kind == "month" else None)
            if check.ok:
                if clipped_note or (ctx.date_start, ctx.date_end) != (resolved.start_iso, resolved.end_iso):
                    ctx.date_note = (
                        f"Interpreted '{resolved.label}' as {resolved.start_iso} to {resolved.end_iso}{clipped_note} "
                        f"(relative dates are anchored to {_iso(reference_date())}, the end of the dataset)."
                    )
                ctx.date_start, ctx.date_end = resolved.start_iso, resolved.end_iso
                ctx.date_status, ctx.date_source = "valid", "deterministic"
                return
            ctx.date_status = "invalid"
            ctx.date_note = f"Could not use '{resolved.label}': " + "; ".join(check.problems) + "."
            ctx.date_start = ctx.date_end = None
            ctx.confidence = "low"
            return

        if ctx.date_start or ctx.date_end:
            check = validate_range(ctx.date_start, ctx.date_end or ctx.date_start)
            if check.ok:
                ctx.date_end = ctx.date_end or ctx.date_start
                ctx.date_status, ctx.date_source = "valid", "router"
                return
            ctx.date_status = "invalid"
            ctx.date_note = (
                "The date range could not be interpreted ("
                + "; ".join(check.problems)
                + "), so it was not used."
            )
            ctx.date_start = ctx.date_end = None
            ctx.confidence = "low"
            return

        ctx.date_status, ctx.date_source = "none", "none"

    @staticmethod
    def _routing_confidence(ctx: QueryContext, router_label: str, router_dates: tuple) -> tuple[str, List[str]]:
        """Confidence from evidence, not the 3B router's self-report (which said "high" for
        nearly everything, including the wrong labels the held-out set exposed).

        low: the router's label was overridden by the user's words, or its extraction failed (regex
        fallback). medium: the label stood but the dates were re-derived from the text. high: label
        and dates agreed with the deterministic checks.

        An impossible date in the question ("2024-06-31") used to make it low. It is the user's
        date, not a routing error, and the plan already carries a notice: all 5 such dev questions
        were planned correctly by both routers (2026-10-09), so it no longer lowers the level.
        """
        reasons = []
        if ctx.intent_category != router_label:
            reasons.append(f"router label '{router_label}' overridden to '{ctx.intent_category}'")
        if ctx.confidence == "low" and not reasons:
            reasons.append("router extraction fell back to rules")
        if reasons:
            return "low", reasons
        if ctx.date_source == "deterministic" and router_dates != (ctx.date_start, ctx.date_end):
            return "medium", [f"router dates {router_dates[0]}..{router_dates[1]} replaced from the text"]
        return "high", []

    @staticmethod
    def _queried_window(plan: QueryPlan) -> Optional[str]:
        """The date window the plan will actually query, read from its first step."""
        for step in plan.steps:
            p = step.params
            if p.get("start_date") and p.get("end_date"):
                return f"{p['start_date']} to {p['end_date']}"
            if p.get("query_date"):
                return p["query_date"]
        return None

    def _recover_location(self, ctx: QueryContext) -> None:
        """Fill ``ctx.location`` from the user's words when the router left it empty.

        The router sometimes puts the place into query_text instead
        ("how has California been this month" -> location=None).
        """
        if ctx.location:
            return
        # Short names ("US") only match as written, so "tell us" is not the United States.
        loc = find_known_location(ctx.user_input or "")
        if loc:
            ctx.location = loc

    def _comparison_plan(self, ctx: QueryContext, periods: tuple[DateRange, DateRange]) -> QueryPlan:
        """Plan for "did X increase": two complete periods, counted, then compared."""
        earlier, later = periods
        text = ctx.user_input or ""
        self._recover_location(ctx)
        if not ctx.event_type:
            lowered = text.lower()
            if any(w in lowered for w in ("protest", "demonstration", "rally")):
                ctx.event_type = "protest"
            elif any(w in lowered for w in ("conflict", "attack", "clash", "battle")):
                ctx.event_type = "conflict"
            elif any(w in lowered for w in ("cooperation", "treaty", "agreement", "partnership")):
                ctx.event_type = "cooperation"
        params: Dict[str, Any] = {
            "periods": [
                {"label": earlier.label, "start": earlier.start_iso, "end": earlier.end_iso},
                {"label": later.label, "start": later.start_iso, "end": later.end_iso},
            ],
        }
        if ctx.location:
            params["location_hint"] = ctx.location
        if ctx.event_type:
            params["event_type"] = ctx.event_type
        where = f" in {ctx.location}" if ctx.location else ""
        what = ctx.event_type or "event"
        notes = [
            f"Comparing {what} counts{where}: {earlier.label} ({earlier.start_iso} to {earlier.end_iso}) "
            f"vs {later.label} ({later.start_iso} to {later.end_iso}). "
            f"Relative dates are anchored to {_iso(reference_date())}, the end of the dataset."
        ]
        if not ctx.location:
            notes.append("No location was recognised, so counts cover the whole dataset region.")
        return QueryPlan(
            intent=f"compare_periods_{ctx.event_type or 'all'}_{ctx.location or 'global'}",
            thinking=(
                f"The question compares two periods, so I count every matching event in {earlier.label} "
                f"and {later.label} and compute the change deterministically instead of summarising a sample."
            ),
            time_range={"start": earlier.start_iso, "end": later.end_iso},
            steps=[QueryStep(type="compare_periods", params=params)],
            visualizations=["comparison", "report"],
            report_prompt=(
                f"Explain this period comparison for {what} events{where}. "
                "Quote the verdict and the counts exactly as given and do not recompute them."
            ),
            notice=" ".join(notes),
        )

    # -----------------------------------------------------------------------
    # LLM Tool Planner
    # -----------------------------------------------------------------------

    async def _llm_plan(self, query: str, ctx: QueryContext) -> QueryPlan:
        """Use remote LLM for complex queries. Passes simplified context extracted by Ollama."""
        # Build simplified user intent from structured context
        parts = []
        if ctx.location:
            parts.append(f"Location: {ctx.location}")
        if ctx.date_start:
            if ctx.date_start == ctx.date_end:
                parts.append(f"Date: {ctx.date_start}")
            else:
                parts.append(f"Date range: {ctx.date_start} to {ctx.date_end}")
        if ctx.event_type:
            parts.append(f"Event type: {ctx.event_type}")
        if ctx.query_text:
            parts.append(f"Search terms: {ctx.query_text}")
        
        simplified = "; ".join(parts) if parts else query
        
        # Also attach original query as reference
        user_msg = (
            f"Reference date (treat as today): {_iso(reference_date())}\n"
            f"Simplified user intent: {simplified}\n\nOriginal request: \"{query}\""
        )
        
        # Add any extra context from Ollama
        context_parts = []
        if ctx.intent_category != "search":
            context_parts.append(f"Intent category: {ctx.intent_category}")
        context_str = "\n".join(context_parts) if context_parts else ""
        if context_str:
            user_msg += f"\n\nExtracted context:\n{context_str}"
        user_msg += "\n\nRespond with ONLY raw JSON:"

        messages = [
            SystemMessage(content=PLANNER_SYSTEM_PROMPT),
            HumanMessage(content=user_msg),
        ]

        try:
            response = await asyncio.wait_for(self.llm.ainvoke(messages), timeout=120.0)
            content = response.content if hasattr(response, "content") else str(response)
            print(f"[Planner] raw response length: {len(content)}", flush=True)

            raw = _extract_json(content)
            if raw is None:
                # Print full response for debugging (truncated if very long)
                debug_content = content if len(content) < 800 else content[:400] + "\n... [truncated]\n" + content[-200:]
                print(f"[Planner] JSON extraction failed. Raw response:\n{debug_content}", flush=True)
                raise ValueError("Could not extract valid JSON from LLM response")

            plan = _normalize_plan(raw)
            print(f"[Planner] generated plan: {plan.intent} with {len(plan.steps)} steps", flush=True)
            return plan

        except asyncio.TimeoutError:
            print(f"[Planner] LLM timeout after 120s, using fallback plan", flush=True)
            return self._fallback_plan(query)
        except Exception as e:
            print(f"[Planner] failed: {e}, using fallback plan", flush=True)
            return self._fallback_plan(query)

    def _fallback_plan(self, query: str) -> QueryPlan:
        """Fallback when LLM or router fails."""
        return QueryPlan(
            intent="fallback_search",
            thinking="Planner error. Falling back to top events search.",
            steps=[QueryStep(type="top_events", params={"top_n": 20, "start_date": DEFAULT_DATA_START, "end_date": DEFAULT_DATA_END})],
            visualizations=["event_table", "report"],
            report_prompt=f"Top events for: {query}",
            notice="Planner error. Showing top-ranked events across the full dataset (fast mode). Add a month or date for more precise results.",
        )

    # -----------------------------------------------------------------------
    # Main Entry Point
    # -----------------------------------------------------------------------

    async def plan(self, user_query: str) -> tuple[QueryPlan, List[Dict[str, Any]]]:
        """Generate a query plan from user input.
        
        Simple flow:
        1. Ollama extracts structured context (location, date, event_type, intent).
        2. Rule-based planner directly maps context to tool calls.
        3. Only truly ambiguous queries fall back to remote LLM.
        Returns (QueryPlan, phases).
        """
        import time
        phases: List[Dict[str, Any]] = []
        stripped = user_query.strip()

        # Fast path: greetings (avoid even calling router)
        if self._GREETING_PATTERNS.match(stripped) or len(stripped) < 3:
            print(f"[Planner] Fast off-topic detected for: '{stripped}'", flush=True)
            return QueryPlan(
                intent="off_topic",
                steps=[],
                visualizations=[],
                report_prompt=None,
            ), [{"name": "Intent Check", "status": "completed", "detail": "Greeting or too-short input detected — skipping AI.", "elapsed_ms": 0}]

        # Fast path: an event ID anywhere in the sentence is deterministic, no LLM needed.
        id_match = EVENT_ID_IN_TEXT.search(stripped)
        if id_match:
            ctx = QueryContext(
                user_input=stripped,
                intent_category="detail",
                query_text=id_match.group(0),
                confidence="high",
            )
            t0 = time.time()
            plan = self._rule_based_plan(ctx)
            if plan:
                step_types = " → ".join(s.type for s in plan.steps)
                return plan, [{
                    "name": "Event ID Match",
                    "status": "completed",
                    "detail": f"Event ID '{id_match.group(0)}' found in the query | Tools: {step_types}",
                    "elapsed_ms": round((time.time() - t0) * 1000, 1),
                }]

        # Phase 1: Context Extraction (Ollama)
        t0 = time.time()
        ctx = await self.router.extract_context(stripped)
        ctx.user_input = stripped  # Preserve original query
        t_router = round((time.time() - t0) * 1000, 1)

        router_label, router_dates = ctx.intent_category, (ctx.date_start, ctx.date_end)

        # Phase 1b: deterministic, validated dates (overrides the router's dates)
        self._resolve_dates(ctx, stripped)

        # Phase 1b': the router's label must agree with the user's words.
        #  * "detail" without an event ID: real IDs never reach the router (fast path above).
        #    The router called "Were there more protests in Texas in October than in September?" detail.
        #  * "brief" with no briefing words: "news about the march on Washington DC" became a
        #    one-day brief for yesterday.
        #  * a briefing word and a single day, labelled search, or overview with no place (which
        #    cannot run as an overview): "give me a recap of 2024-11-05" got both labels.
        if ctx.intent_category == "detail":
            ctx.intent_category = "search"
        elif ctx.intent_category == "brief" and not _BRIEF_RE.search(stripped):
            ctx.intent_category = "search"
        elif ((ctx.intent_category == "search" or (ctx.intent_category == "overview" and not ctx.location))
              and _BRIEF_RE.search(stripped) and ctx.date_start and ctx.date_start == ctx.date_end):
            ctx.intent_category = "brief"
        if ctx.intent_category == "search" and _HOT_RE.search(stripped):
            # "biggest news on 2024-07-04": the router said brief (no briefing word, so search
            # above) or search; the words ask for the most-covered events (held-out v2).
            ctx.intent_category = "hot"

        # Phase 1c: "how has California been this month" asks about a region as a whole.
        # The 3B router labels it brief or search depending on the state name, and for
        # California it also dropped the location.
        if ctx.intent_category in ("search", "brief") and _OVERVIEW_RE.search(stripped):
            self._recover_location(ctx)
            if ctx.location:
                ctx.intent_category = "overview"
        elif ctx.intent_category == "overview" and not ctx.location:
            # Right label, place dropped: "overview of British Columbia this year" (held-out v2).
            self._recover_location(ctx)

        routing_confidence, routing_reasons = self._routing_confidence(ctx, router_label, router_dates)
        if isinstance(self.router, ClaudeRouter) and ctx.router not in (self.router.model, "rules"):
            routing_reasons.append(f"Claude router unavailable, {ctx.router} used")
            if routing_confidence == "high":
                routing_confidence = "medium"

        detail_parts = [f"intent='{ctx.intent_category}'"]
        if ctx.location:
            detail_parts.append(f"loc='{ctx.location}'")
        if ctx.date_start:
            detail_parts.append(f"date={ctx.date_start} to {ctx.date_end} [{ctx.date_source}, {ctx.date_status}]")
        elif ctx.date_status == "invalid":
            detail_parts.append("date=invalid, not used")
        if ctx.event_type:
            detail_parts.append(f"type='{ctx.event_type}'")
        if ctx.query_text:
            detail_parts.append(f"text='{ctx.query_text}'")
        
        print(f"[Planner] Context: {', '.join(detail_parts)} | confidence={ctx.confidence} in {t_router}ms", flush=True)
        phases.append({
            "name": "Context Extraction",
            "status": "completed",
            "detail": f"{ctx.router or 'Router'} extracted: {', '.join(detail_parts)} ({ctx.confidence} confidence)",
            "elapsed_ms": t_router,
        })
        phases.append({
            "name": "Routing Check",
            "status": "completed",
            "detail": f"routing confidence {routing_confidence}" + (f": {'; '.join(routing_reasons)}" if routing_reasons else ""),
            "elapsed_ms": 0,
        })

        if ctx.intent_category == "off_topic":
            return QueryPlan(
                intent="off_topic",
                steps=[],
                visualizations=[],
                report_prompt=None,
            ), phases

        # Phase 2a: period comparison ("did X increase this month?"): count two complete
        # periods and compare, rather than summarising a top-N sample. Decided from the
        # user's words, not the router's label: the router called "Did protests increase
        # in Canada in March compared with February?" a daily brief.
        comparison = resolve_comparison_periods(stripped) if ctx.intent_category != "detail" else None
        if comparison:
            # "Did protests increase in January?" compares with December 2023, which is not in
            # the dataset: the count there is unknown, not zero ("December 2023 had none" was
            # the verdict). Compare only periods that overlap the data; cut partial ones.
            earlier, later = comparison
            earlier_in, later_in = clip_to_dataset(earlier), clip_to_dataset(later)
            if earlier_in is None or later_in is None:
                missing = earlier if earlier_in is None else later
                kept = later_in or earlier_in
                ctx.date_note = (
                    f"The dataset covers {DEFAULT_DATA_START} to {DEFAULT_DATA_END}, so {later.label} cannot be "
                    f"compared with {earlier.label}: there is no data for {missing.label}"
                    + (f". Showing {kept.label} only." if kept else ".")
                )
                if kept:
                    ctx.date_start, ctx.date_end = kept.start_iso, kept.end_iso
                comparison = None
            else:
                comparison = (earlier_in, later_in)
        if comparison:
            t0 = time.time()
            compare_plan = self._comparison_plan(ctx, comparison)
            compare_plan.routing_confidence = routing_confidence
            t_plan = round((time.time() - t0) * 1000, 1)
            phases.append({
                "name": "Comparison Planning",
                "status": "completed",
                "detail": f"Two periods resolved: {comparison[0].label} vs {comparison[1].label} | Tools: compare_periods",
                "elapsed_ms": t_plan,
            })
            return compare_plan, phases

        # Phase 2: Rule-Based Plan Generation — direct tool mapping, no LLM for simple queries
        t0 = time.time()
        fast_plan = self._rule_based_plan(ctx)
        if fast_plan:
            fast_plan.routing_confidence = routing_confidence
            if ctx.date_note and not fast_plan.notice:
                fast_plan.notice = ctx.date_note
                window = self._queried_window(fast_plan) if ctx.date_status == "invalid" else None
                if window:
                    fast_plan.notice += f" Showing {window} instead."
            t_plan = round((time.time() - t0) * 1000, 1)
            step_types = ' → '.join(s.type for s in fast_plan.steps)
            detail = f"Matched '{fast_plan.intent}' | Tools: {step_types}"
            print(f"[Planner] Rule-based plan: {fast_plan.intent} with {len(fast_plan.steps)} steps in {t_plan}ms", flush=True)
            phases.append({"name": "Rule-Based Planning", "status": "completed", "detail": detail, "elapsed_ms": t_plan})
            return fast_plan, phases
        
        # Fallback: remote LLM for truly ambiguous queries
        print(f"[Planner] Rule base couldn't match, falling back to remote LLM", flush=True)
        plan = await self._llm_plan(stripped, ctx)
        plan.routing_confidence = "low"  # the rules could not plan it
        t_plan = round((time.time() - t0) * 1000, 1)
        step_types = ' → '.join(s.type for s in plan.steps)
        detail = f"Remote LLM generated plan | Tools: {step_types}"
        phases.append({"name": "AI Planning", "status": "completed", "detail": detail, "elapsed_ms": t_plan})
        return plan, phases


