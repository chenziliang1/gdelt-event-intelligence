# provider -> (API key env vars in order, default base URL, default model).
# Claude is reached through Anthropic's OpenAI-compatible endpoint, so ChatOpenAI works unchanged.
_LLM_PROVIDERS = {
    "claude": (("ANTHROPIC_API_KEY",), "https://api.anthropic.com/v1/", "claude-sonnet-5-5"),
    "openai": (("OPENAI_API_KEY",), "https://api.openai.com/v1", "gpt-4o"),
}
_LLM_PROVIDER_ALIASES = {"anthropic": "claude"}


def resolve_llm_settings(config: Optional[Dict[str, Any]] = None) -> Dict[str, str]:
    """Provider, key, base URL and model from runtime config, then environment.

    LLM_BASE_URL / LLM_MODEL apply only to the provider named in LLM_PROVIDER: they used to
    apply to every provider, so switching provider sent the new key to the old base URL.
    """
    cfg = config or {}
    env_provider = os.getenv("LLM_PROVIDER", "claude").lower()
    env_provider = _LLM_PROVIDER_ALIASES.get(env_provider, env_provider)
    provider = str(cfg.get("provider") or env_provider).lower()
    provider = _LLM_PROVIDER_ALIASES.get(provider, provider)
    if provider not in _LLM_PROVIDERS:
        raise ValueError(f"Unknown LLM provider: {provider}")

    key_vars, default_url, default_model = _LLM_PROVIDERS[provider]
    from_env = provider == env_provider
    api_key = cfg.get("api_key") or next((os.getenv(v) for v in key_vars if os.getenv(v)), "")
    return {
        "provider": provider,
        "api_key": api_key,
        "base_url": cfg.get("base_url") or (os.getenv("LLM_BASE_URL") if from_env else None) or default_url,
        "model": cfg.get("model") or (os.getenv("LLM_MODEL") if from_env else None) or default_model,
    }


def build_llm(config: Optional[Dict[str, Any]] = None) -> ChatOpenAI:
    """Initialize LLM from environment or runtime config."""
    settings = resolve_llm_settings(config)
    if not settings["api_key"]:
        raise ValueError(f"API key not set for provider: {settings['provider']}")

    # Current Claude models reject `temperature` ("deprecated for this model"); others keep 0.1.
    sampling = {} if settings["provider"] == "claude" else {"temperature": 0.1}
    return ChatOpenAI(
        api_key=settings["api_key"],
        base_url=settings["base_url"],
        model=settings["model"],
        max_tokens=4096,
        **sampling,
    )


