# Event IDs anywhere in a sentence: EVT-2024-01-09-123, a fingerprint such as
# US-20240109-FOR-PROTEST-1150442224 (any 2-letter country: CA-..., MX-...), or a bare 9-12 digit ID.
EVENT_ID_IN_TEXT = re.compile(
    r'\b(EVT-\d{4}-\d{2}-\d{2}-\d+|[A-Z]{2}-\d{8}-[A-Z]+-[A-Z]+-\d+)\b|(?<![\d-])(\d{9,12})(?![\d-])',
    re.IGNORECASE,
)

_BRIEF_RE = re.compile(
    r"\b(daily brief|brief|briefing|what happened|what was|summari[sz]e|summary|recap|digest|rundown)\b",
    re.IGNORECASE,
)
_OVERVIEW_RE = re.compile(
    r"\b(overview|situation|what'?s happening|state of"
    r"|how\s+(?:has|have|is|are|was|were)\s+(?:\w+\s+){1,4}(?:been|doing|going))\b",
    re.IGNORECASE,
)
_HOT_RE = re.compile(
    r"\b(hottest|hot|trending|top\s+\d*\s*(?:events?|news|stories|headlines)|"
    r"(?:biggest|largest|major)\s+(?:events?|news|stories|headlines)|"
    r"most\s+(?:popular|reported|mentioned|important|covered))\b",
    re.IGNORECASE,
)


def context_from_router_json(raw: Dict, query: str) -> QueryContext:
    """QueryContext from a router's JSON reply (same schema for the Claude and the local router)."""
    def field(name):
        value = raw.get(name)
        if isinstance(value, str) and value.strip().lower() in ('null', 'none', 'n/a', ''):
            return None
        return value

    location, event_type, query_text = field("location"), field("event_type"), field("query_text")
    date_start, date_end = field("date_start"), field("date_end")
    intent = raw.get("intent_category", "search")
    if intent not in ("search", "detail", "brief", "overview", "hot", "off_topic"):
        intent = "search"

    # If query_text looks like an event fingerprint, force intent=detail and clear all other
    # fields (fingerprint lookup does not need date/location filters).
    check_text = (query_text or "").strip() or query.strip()
    if re.match(r'^(EVT-\d{4}-\d{2}-\d{2}-\d+|US-\d{8}-[A-Z]+-[A-Z]+-\d+|\d{9,12})$', check_text, re.IGNORECASE):
        intent = "detail"
        location = date_start = date_end = event_type = None
        query_text = query_text or check_text

    return QueryContext(
        location=location,
        date_start=date_start,
        date_end=date_end,
        event_type=event_type,
        query_text=query_text,
        intent_category=intent,
        confidence="high",
    )


def detect_intent(text: str) -> str:
    """Keyword intent detection shared by the regex fallback paths."""
    if _BRIEF_RE.search(text):
        return "brief"
    if _OVERVIEW_RE.search(text):
        return "overview"
    if _HOT_RE.search(text):
        return "hot"
    return "search"


class OllamaRouter:
    """Fast local intent router using qwen2.5:3b via Ollama.
    
    Routes queries to one of three categories:
    - rule_base: Simple lookups with explicit filters (time, location, event type, ID)
    - llm_tools: Complex queries requiring reasoning/comparison/synthesis
    - off_topic: Greetings, small talk, unrelated questions
    
    Tries multiple URLs in order (env var → host.docker.internal → localhost)
    to support both Docker and native environments.
    """

    MODEL = "qwen2.5:3b"

    def _get_urls(self) -> list[str]:
        """Return candidate Ollama URLs to try."""
        urls = []
        env_url = os.getenv("OLLAMA_URL")
        if env_url:
            urls.append(env_url)
        # Docker Desktop / host network
        urls.append("http://host.docker.internal:11434/api/generate")
        # Native / Linux Docker with host network
        urls.append("http://localhost:11434/api/generate")
        return urls

    SYSTEM_PROMPT = """You extract structured information from natural language queries for a GDELT event search system.

Extract and return ONLY this JSON format:
{
  "location": "canonical location name or null",
  "date_start": "YYYY-MM-DD or null",
  "date_end": "YYYY-MM-DD or null",
  "event_type": "protest|conflict|cooperation or null",
  "query_text": "free text search terms or null",
  "intent_category": "search|detail|brief|overview|hot|off_topic"
}

Date extraction rules:
- "May 1 2024" → "2024-05-01" to "2024-05-01"
- "Jan 2024" → "2024-01-01" to "2024-01-31"
- "Q1 2024" → "2024-01-01" to "2024-03-31"
- "last week" → the previous Monday-to-Sunday week before the reference date
- "recently" → last 30 days
- "2024" → "2024-01-01" to "2024-12-31"
- null → "2024-01-01" to "2024-12-31"

Location canonicalization:
- "NYC", "NY", "New York City" → "New York"
- "DC", "Washington DC", "Washington, D.C." → "Washington DC"
- "LA" → "Los Angeles"
- "SF" → "San Francisco"
- "TX" → "Texas"

Event type mapping:
- "protest", "demonstration", "rally", "march" → "protest"
- "conflict", "war", "attack", "fight", "battle", "clash" → "conflict"
- "cooperation", "treaty", "agreement", "partnership" → "cooperation"

Intent categories:
- "search": general event search (most common)
- "detail": user provided event ID like EVT-2024-01-15-12345 — WHEN INPUT IS AN EVENT ID: set ONLY intent_category="detail" and query_text="the full EVT-... ID", ALL OTHER FIELDS MUST BE null
- "brief": "daily brief", "what happened on [date]"
- "overview": "situation in [region]", "what's happening in [region]"
- "hot": "hottest event", "top events", "most popular"
- "off_topic": greeting, thanks, small talk

All data is from 2024 only.
No other text. Just the JSON."""

    def __init__(self):
        self._client: Optional[httpx.AsyncClient] = None
        # Compile fallback patterns once
        self._EVENT_ID_PATTERN = re.compile(
            r'^(EVT-\d{4}-\d{2}-\d{2}-\d+)\b|'
            r'^(US-\d{8}-[A-Z]+-[A-Z]+-\d+)\b|'
            r'^\d{9,12}\b',
            re.IGNORECASE,
        )
        # Unanchored: finds the ID inside a sentence ("tell me about event 1150442224").
        # The anchored pattern above only matches when the whole input starts with the ID,
        # which is why natural-language ID lookups never reached the event_detail tool.
        self._EVENT_ID_IN_TEXT = EVENT_ID_IN_TEXT
        self._GREETING_PATTERNS = re.compile(
            r'^(hi|hello|hey|greetings|good morning|good afternoon|good evening|thanks|thank you|bye|goodbye|ok|okay)\b',
            re.IGNORECASE,
        )
        self._MONTH_YEAR_PATTERN = re.compile(
            r'\b(jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*\s+(\d{4})\b',
            re.IGNORECASE,
        )
        self._FULL_DATE_PATTERN = re.compile(
            r'\b(\d{4})[-/](\d{1,2})[-/](\d{1,2})\b|'
            r'\b(\d{1,2})[-/](\d{1,2})[-/](\d{4})\b|'
            r'\b(\d{4})(\d{2})(\d{2})\b',
        )
        self._LOCATION_PATTERN = re.compile(
            r'\b(?:in|at|near|around|on)\s+([A-Z][A-Za-z\s,]+?)(?=\s+(?:in|at|near|around|on|during|for|from|to|of|with|this|last|'
            r'\d{4}|(?:jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*|\?|$)|$)',
            re.IGNORECASE,
        )
        self._MONTH_MAP = {
            'jan': '01', 'feb': '02', 'mar': '03', 'apr': '04', 'may': '05', 'jun': '06',
            'jul': '07', 'aug': '08', 'sep': '09', 'oct': '10', 'nov': '11', 'dec': '12',
        }

    @property
    def client(self) -> httpx.AsyncClient:
        if self._client is None:
            self._client = httpx.AsyncClient(timeout=httpx.Timeout(10.0, connect=2.0))
        return self._client

    async def extract_context(self, query: str) -> QueryContext:
        """Extract structured context from natural language query.
        Tries each Ollama URL in order. Falls back to regex-based extraction on total failure.
        """
        prompt = (
            f"{self.SYSTEM_PROMPT}\n\n"
            f"Reference date for relative phrases (treat this as 'today'): {_iso(reference_date())}\n\n"
            f"Query: \"{query}\"\n\nJSON:"
        )
        last_error = None
        
        for url in self._get_urls():
            try:
                resp = await self.client.post(
                    url,
                    json={
                        "model": self.MODEL,
                        "prompt": prompt,
                        "stream": False,
                        "options": {"temperature": 0.0, "num_predict": 120},
                    },
                )
                resp.raise_for_status()
                data = resp.json()
                text = data.get("response", "").strip()
                
                raw = _extract_json(text)
                if raw is None:
                    continue
                ctx = context_from_router_json(raw, query)
                ctx.router = self.MODEL
                return ctx

            except Exception as e:
                last_error = e
                continue
        
        print(f"[OllamaRouter] All URLs failed (last: {last_error}), falling back to regex extraction", flush=True)
        ctx = self._fallback_extract_context(query)
        ctx.router = "rules"
        return ctx

    def _fallback_extract_context(self, query: str) -> QueryContext:
        """Regex-based fallback extraction when Ollama router fails."""
        q = query.lower().strip()
        
        # Greeting check
        if len(q) < 3 or self._GREETING_PATTERNS.match(q):
            return QueryContext(intent_category="off_topic", confidence="low")
        
        # Event ID check
        evt_match = self._EVENT_ID_IN_TEXT.search(query.strip())
        if evt_match:
            return QueryContext(intent_category="detail", confidence="low", query_text=evt_match.group(0))
        
        # Location
        location = None
        loc_match = self._LOCATION_PATTERN.search(query)
        if loc_match:
            location = loc_match.group(1).strip()
        else:
            # Generated from the data (db_scripts/build_known_locations.py): US, Canada, Mexico.
            location = find_known_location(query)
        if location:
            location = re.sub(r'\s+(in|at|near|around|on|during|for|from|to|of|with)$', '', location, flags=re.IGNORECASE).strip()
            if location.lower() in ('dc', 'washington dc', 'washington, dc'):
                location = 'Washington DC'
        
        # Date range
        start_date, end_date = None, None
        nat_match = self._NATURAL_DATE_PATTERN.search(query) if hasattr(self, '_NATURAL_DATE_PATTERN') else None
        if nat_match:
            if nat_match.group(1):
                month_abbr = nat_match.group(1).lower()[:3]
                d = nat_match.group(2).zfill(2)
                y = nat_match.group(3)
                start_date = f"{y}-{self._MONTH_MAP.get(month_abbr, '01')}-{d}"
                end_date = start_date
            elif nat_match.group(4):
                d = nat_match.group(4).zfill(2)
                month_abbr = nat_match.group(5).lower()[:3]
                y = nat_match.group(6)
                start_date = f"{y}-{self._MONTH_MAP.get(month_abbr, '01')}-{d}"
                end_date = start_date
        
        if not start_date:
            full_match = self._FULL_DATE_PATTERN.search(query)
            if full_match:
                if full_match.group(1):
                    start_date = f"{full_match.group(1)}-{full_match.group(2).zfill(2)}-{full_match.group(3).zfill(2)}"
                    end_date = start_date
                elif full_match.group(4):
                    start_date = f"{full_match.group(6)}-{full_match.group(4).zfill(2)}-{full_match.group(5).zfill(2)}"
                    end_date = start_date
                elif full_match.group(7):
                    start_date = f"{full_match.group(7)}-{full_match.group(8)}-{full_match.group(9)}"
                    end_date = start_date
        
        if not start_date:
            my_match = self._MONTH_YEAR_PATTERN.search(query)
            if my_match:
                month_abbr = my_match.group(1).lower()[:3]
                y = my_match.group(2)
                m = self._MONTH_MAP.get(month_abbr, '01')
                first, last = month_bounds(int(y), int(m))
                start_date, end_date = _iso(first), _iso(last)
        
        # Event type
        event_type = None
        if 'protest' in q or 'demonstration' in q or 'rally' in q or 'march' in q:
            event_type = 'protest'
        elif 'conflict' in q or 'war' in q or 'attack' in q or 'fight' in q or 'battle' in q or 'clash' in q:
            event_type = 'conflict'
        elif 'cooperation' in q or 'treaty' in q or 'agreement' in q or 'partnership' in q:
            event_type = 'cooperation'
        
        # The fallback used to return intent="search" for everything, so a "daily brief"
        # or "regional overview" question was misrouted to a generic event search.
        intent = detect_intent(q)

        return QueryContext(
            intent_category=intent,
            confidence="low",
            location=location,
            date_start=start_date,
            date_end=end_date,
            event_type=event_type,
            query_text=query.strip(),
        )

    async def extract_context_fast(self, query: str) -> QueryContext:
        """Fast-path context extraction using regex only — no Ollama call.
        
        Used for queries with obvious structured filters (date, location, event_type)
        where we don't need LLM reasoning. Returns in < 5ms vs 2s for Ollama.
        """
        import time
        t0 = time.time()
        
        q_lower = query.lower()
        
        # Date extraction
        date_start, date_end = None, None
        
        # Full date: "Jan 25 2024", "January 25, 2024", "2024-01-25"
        m = re.search(r'(?:jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*\.?\s+(\d{1,2})(?:st|nd|rd|th)?[,\s]+(2024)', q_lower)
        if m:
            month_map = {'jan':1,'feb':2,'mar':3,'apr':4,'may':5,'jun':6,
                         'jul':7,'aug':8,'sep':9,'oct':10,'nov':11,'dec':12}
            month_abbr = q_lower[m.start():m.start()+3]
            month = month_map.get(month_abbr, 1)
            day = int(m.group(1))
            date_start = date_end = f"2024-{month:02d}-{day:02d}"
        else:
            m = re.search(r'(\d{4})-(\d{2})-(\d{2})', query)
            if m:
                date_start = date_end = m.group(0)
        
        # Month only: "feb 2024", "in february"
        if not date_start:
            m = re.search(r'(?:jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*', q_lower)
            if m:
                month_map = {'jan':1,'feb':2,'mar':3,'apr':4,'may':5,'jun':6,
                             'jul':7,'aug':8,'sep':9,'oct':10,'nov':11,'dec':12}
                month_abbr = q_lower[m.start():m.start()+3]
                month = month_map.get(month_abbr, 1)
                first, last = month_bounds(2024, month)
                date_start, date_end = _iso(first), _iso(last)
        
        # Location extraction
        location = None
        loc_patterns = [
            (r'(?:near|in|around)\s+(?:the\s+)?white\s+house', 'Washington DC'),
            (r'(?:near|in|around)\s+(?:washington\s+dc?|washington,\s*d\.?c\.?)', 'Washington DC'),
            (r'(?:near|in|around)\s+(?:new\s+york\s+city?|nyc|new\s+york)', 'New York'),
            (r'(?:near|in|around)\s+(?:los\s+angeles|la)', 'Los Angeles'),
            (r'(?:near|in|around)\s+(?:san\s+francisco|sf)', 'San Francisco'),
            (r'(?:near|in|around)\s+texas', 'Texas'),
            (r'(?:near|in|around)\s+california', 'California'),
            (r'(?:near|in|around)\s+florida', 'Florida'),
        ]
        for pattern, canonical in loc_patterns:
            if re.search(pattern, q_lower):
                location = canonical
                break
        
        # Event type extraction
        event_type = None
        if 'protest' in q_lower or 'demonstration' in q_lower or 'rally' in q_lower:
            event_type = 'protest'
        elif 'conflict' in q_lower or 'war' in q_lower or 'attack' in q_lower:
            event_type = 'conflict'
        elif 'cooperation' in q_lower or 'treaty' in q_lower or 'agreement' in q_lower:
            event_type = 'cooperation'
        
        # Intent: brief if "what happened", otherwise search
        intent = 'search'
        if re.search(r'what\s+happened|daily\s+brief|what\s+was', q_lower):
            intent = 'brief'
        
        # Query text: strip out obvious filter words to keep only meaningful search terms
        query_text = query
        
        elapsed_ms = round((time.time() - t0) * 1000, 3)
        print(f"[OllamaRouter] Fast-path regex extraction: {elapsed_ms}ms | loc={location}, date={date_start}, type={event_type}, intent={intent}", flush=True)
        
        return QueryContext(
            location=location,
            date_start=date_start,
            date_end=date_end,
            event_type=event_type,
            query_text=query_text,
            intent_category=intent,
            confidence="high" if validate_range(date_start, date_end).ok or not date_start else "low",
        )

    async def close(self):
        if self._client:
            await self._client.aclose()
            self._client = None


class ClaudeRouter:
    """Context extraction with Claude (ROUTER_MODEL, default claude-sonnet-5-5), same JSON schema
    and prompt as the local router.

    The 3B router mislabelled questions the rules had not been written for (each new held-out set
    needed new rule fixes), so the default router is now Claude, with the local model as the
    fallback when there is no key or the call fails (and the regex rules behind that). The
    planner's deterministic checks (dates, labels against the user's words) apply to either router.
    """

    def __init__(self, fallback: Optional["OllamaRouter"] = None, config: Optional[Dict[str, Any]] = None):
        self.fallback = fallback or OllamaRouter()
        self._config = config
        self._llm: Optional[ChatOpenAI] = None
        self.model = os.getenv("ROUTER_MODEL", "claude-sonnet-5-5")

    def _client(self) -> ChatOpenAI:
        if self._llm is None:
            cfg = dict(self._config or {}, provider="claude", model=self.model)
            settings = resolve_llm_settings(cfg)
            if not settings["api_key"]:
                raise ValueError("ANTHROPIC_API_KEY not set")
            # max_tokens covers the model's reasoning as well as the JSON: at 300, Sonnet 5.5 spent
            # the whole budget reasoning about impossible dates and "this week" and returned no text
            # (finish_reason=length) on 12 of 118 eval questions.
            self._llm = ChatOpenAI(api_key=settings["api_key"], base_url=settings["base_url"],
                                   model=settings["model"], max_tokens=2048, timeout=30, max_retries=1)
        return self._llm

    async def extract_context(self, query: str) -> QueryContext:
        messages = [
            SystemMessage(content=OllamaRouter.SYSTEM_PROMPT),
            HumanMessage(content=(
                f"Reference date for relative phrases (treat this as 'today'): {_iso(reference_date())}\n\n"
                f"Query: \"{query}\"\n\nJSON:")),
        ]
        try:
            response = await self._client().ainvoke(messages)
            raw = _extract_json(response.content if hasattr(response, "content") else str(response))
            if raw is None:
                raise ValueError("no JSON in the router reply")
            ctx = context_from_router_json(raw, query)
            ctx.router = self.model
            return ctx
        except Exception as e:
            print(f"[ClaudeRouter] {type(e).__name__}: {e}; using the local router", flush=True)
            return await self.fallback.extract_context(query)

    async def close(self):
        await self.fallback.close()


def build_router():
    """ROUTER_PROVIDER=claude (default) or ollama (local qwen2.5:3b only)."""
    if os.getenv("ROUTER_PROVIDER", "claude").lower() == "ollama":
        return OllamaRouter()
    return ClaudeRouter()


